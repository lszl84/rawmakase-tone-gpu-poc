#!/usr/bin/env python3
"""Turns RAWmakase's measured tone tables into one float array for the GPU.

Reads basic_tone_data.rs and local_tone_data.rs from a RAWmakase checkout and writes
a header with the values packed in one array, and the offsets of each table, for
both C++ (`tables.h`) and GLSL (`tables.glsl`). Nothing is copied by hand, so the
POC always uses the checkout's tables.

    gen_tables.py RAWMAKASE_DIR OUT_DIR
"""
import re
import sys
from pathlib import Path

NUMBER = re.compile(r"-?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?")


def consts(text):
    """`name -> literal text` for each `pub(super) const NAME: TYPE = LITERAL;`."""
    out = {}
    for m in re.finditer(r"pub\(super\) const (\w+)\s*:[^=]*=", text):
        start = m.end()
        depth, i = 0, start
        while True:
            c = text[i]
            if c in "[{(":
                depth += 1
            elif c in "]})":
                depth -= 1
            elif c == ";" and depth == 0:
                break
            i += 1
        out[m.group(1)] = text[start:i]
    return out


def numbers(literal, expected):
    values = [float(v) for v in NUMBER.findall(literal)]
    if len(values) != expected:
        raise SystemExit(f"expected {expected} values, found {len(values)}")
    return values


def family(literal):
    """percentile, lo, hi, then the 6 x 48 tables, as `Family` declares them."""
    fields = {}
    for name in ("percentile", "lo", "hi"):
        m = re.search(rf"\b{name}\s*:\s*({NUMBER.pattern})", literal)
        fields[name] = float(m.group(1))
    tables = literal[literal.index("tables"):]
    return [fields["percentile"], fields["lo"], fields["hi"]] + numbers(tables, 6 * 48)


def main():
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    develop = root / "crates/rawmakase-engine/src/develop"
    basic = consts((develop / "basic_tone_data.rs").read_text())
    local = consts((develop / "local_tone_data.rs").read_text())

    # (name, values) in the order they are packed.
    blocks = [
        ("BT_SLIDER", numbers(basic["SLIDER_VALUES"], 6)),
        ("BLACKS", numbers(basic["BLACKS"], 6 * 64)),
        ("WHITES", numbers(basic["WHITES"], 6 * 64)),
        ("CONTRAST_CHART", numbers(basic["CONTRAST_CHART"], 6 * 64)),
        ("CONTRAST_PIVOT", numbers(basic["CONTRAST_PIVOT"], 1)),
        ("WHITES_ADAPTIVE", numbers(basic["WHITES_ADAPTIVE"], 13 * 3 * 64)),
        ("WHITES_EXPOSURES", numbers(basic["WHITES_EXPOSURES"], 13)),
        ("WHITES_HIGHLIGHTS", numbers(basic["WHITES_HIGHLIGHTS"], 11)),
        ("LT_SLIDER", numbers(local["SLIDER_VALUES"], 6)),
        ("SHADOWS", family(local["SHADOWS"])),
        ("HIGHLIGHTS", family(local["HIGHLIGHTS"])),
    ]
    values, offsets = [], {}
    for name, v in blocks:
        offsets[name] = len(values)
        values += v
    out.mkdir(parents=True, exist_ok=True)

    cpp = ["// Generated by tools/gen_tables.py from RAWmakase's measured tables.",
           "#pragma once", "namespace tables {"]
    for name, off in offsets.items():
        cpp.append(f"constexpr int {name} = {off};")
    cpp.append(f"constexpr int COUNT = {len(values)};")
    cpp.append("constexpr float DATA[] = {")
    for i in range(0, len(values), 8):
        cpp.append("    " + ", ".join(f"{float(v)!r}f" for v in values[i:i + 8]) + ",")
    cpp += ["};", "} // namespace tables", ""]
    (out / "tables.h").write_text("\n".join(cpp))

    glsl = ["// Generated by tools/gen_tables.py: offsets into the tables buffer."]
    for name, off in offsets.items():
        glsl.append(f"const int T_{name} = {off};")
    glsl.append("")
    (out / "tables.glsl").write_text("\n".join(glsl))


if __name__ == "__main__":
    main()
